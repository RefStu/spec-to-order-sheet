import { buildPrompt } from "./layout";

/**
 * ノード②: 発注書。
 *
 * ⚠ 取り出すのは **ORDER SHEET に出る欄だけ**。
 *   発注書から取るのは Customer PO / Size / QTY / REMARK / 製造番号 / 資材名 の 6 つで、
 *   それ以外は読ませない (読ませると、使われない値のために当てずっぽうが増える)。
 *   ⚠ **発注日 (`orderedOn`) はやめた。** `order_sheets.issued_on` に入るだけで
 *   ORDER SHEET のどのセルにも出ない (DATE は出力した日の日付)。列は残してある。
 *
 * @param formNotes その様式にだけ効く注意書き。**様式が分からなければ空文字**。
 */
export function purchaseOrderPrompt(formNotes = ""): string {
  return buildPrompt(
    {
      overview: `
お客様から届いた**発注書**を 1 通読み、**ヘッダの 1 欄**と**明細の行ごとの 6 欄**を取り出します。
明細は表になっていて、**1 件の明細が表の数行**を占めます。表の見た目の行数ではなく、
**品物 1 件を 1 要素**として返してください。
`,
      fields: `
## ヘッダ

| 欄 | 何の値か | どこから取るか |
| --- | --- | --- |
| customerPoNo | お客様側の**発注No** | **帳票の右上**。見たままの向きで右上をよく見てください。⚠ 明細の中の「オーダーNo」とは**別のもの**です |

## 明細 (品物 1 件につき 1 要素)

| 欄 | 何の値か | どこから取るか |
| --- | --- | --- |
| lineNo | 表の上から数えた順番 (1, 2, 3 …) | ⚠ 印字されている行番号ではありません |
| modelNo | **製造番号** | 「製造番号」の見出しの下。3 帳票を突き合わせる鍵で、**最も大事な項目**です。⚠ 年が 2 桁で印字されていても**印字そのまま** (桁を合わせるのは別の仕事) |
| productName | **資材名** (その品物を作るのに使う材料の名前) | 「資材名」の欄。地金なら「(品位) (材料の種類)」、石なら「(石の種類) (等級) (刻み) (形)」のように材料そのものを指す言葉が並びます |
| sizeText | サイズ (号数や長さ) | 「サイズ」の見出しの下。⚠ **品位のコードを入れないでください** |
| quantity | **本数** (数値) | 「本数」の見出しの下。⚠ 材料の「必要数」ではありません |
| remarkText | 整理の記号 | ⚠⚠ **この欄には見出しがありません。** 「オーダーNo」の**値が入ったセルの、すぐ下のセル**に、**大きめの文字**で**印字**されている値です |
`,
      rules: `
7. **資材名 (productName) は、1 つの明細に複数行あることがあります。**
   その明細のぶんを**すべて、印字の順に改行でつないで**返してください。
   ⚠⚠ **次のものは資材名ではありません。入れないでください。**
   - 「タイトル」「品名」のような、**商品の呼び名や企画の名前**が入る欄
   - 「オーダーNo」の値の真下にある整理の記号 — それは remarkText の担当です。
8. **次のものは読みません。**
   - **発注元の会社名**。差出人・納入場所・受付窓口と複数の会社名が印字されていますが、
     どれを取るべきか決まっていないので取りません。
   - **日付すべて** (発注日・納期・出荷日・渡し日)。印字も手書きもありますが、人が決める欄です。
   - **単位**。決まった値を使うので読みません。
`,
    },
    formNotes,
  );
}
