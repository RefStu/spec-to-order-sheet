import { buildPrompt } from "./layout";

/**
 * ノード③: 新製品依頼書 **1 枚**の欄を読む。
 *
 * ⚠ ORDER SHEET の Description の出どころはこの帳票だけ。
 *   **区分の丸印が読めないと Description は空のまま**になるので、そこだけは文面を厚くしてある。
 * ⚠⚠ **区分は「書き写す」のではなく「様式の選択肢から選ぶ」**。
 *   選択肢は様式の知識なので **`forms/<code>.ts` の注意書き**に書き、この本文には書かない
 *   (様式が増えたときに本文が膨らまないように)。⚠ 契約は `extractedField` のまま (enum にしない)。
 *   選択肢の外の値は web の閉じた集合 (`PREFIX_BY_CATEGORY`) が落とす。
 * ⚠⚠ **代表の図の場所はここでは聞かない**。座標を同じ呼び出しで
 *   聞いていたころは、specNo・品位・品名・区分が**薄くなっていた**。場所は
 *   `prompts/picture-location.ts` の専用ノードが聞く。
 *
 * @param formNotes その様式にだけ効く注意書き。**様式が分からなければ空文字**。
 */
export function specSheetPrompt(formNotes = ""): string {
  return buildPrompt(
    {
      overview: `
お客様から届いた**依頼書**(新製品依頼書・修正変更依頼書)を **1 枚**読み、下の 5 欄を取り出します。
読むだけで、作ることはありません。

⚠⚠ **いま読むのは渡された 1 枚だけです。** 同じ形の依頼書が何枚も届きますが、
**この 1 枚に印字が無い項目は null、表が空なら空の配列**です。
`,
      fields: `
| 欄 | 何の値か | どこから取るか |
| --- | --- | --- |
| specNo | **仕様書No** (製造No) | 「仕様書No」の**見出しの下の行**。発注書の製造番号と同じ番号で、**最も大事な項目**です。印字そのまま |
| productName | 品名 | 「品名」の**見出しの下**。製造番号で結べないときの予備の鍵になります |
| purityText | **品位** (地金の品位を表すコード) | 「品位」の**見出しの下** |
| requestCategoryText | **区分** (丸に囲まれている**選択肢 1 つ**) | **表題のすぐ下の、どの枠にも囲まれていない 1 行** (下の節) |

## 区分の答え方 (表題のすぐ下の行)

区分の行には、**様式の注意書きに挙げた選択肢**がいくつか横に並べて印字され、そのうち
**1 つだけに手書きの丸 (細い楕円) が重なっています**。

- ⚠⚠ **紙の文字を書き写さないでください。選択肢から選んでください。**
  様式の注意書きに挙げた選択肢のうち、**丸で囲まれている 1 つ**を、**注意書きの表記のまま**返します。
  ⚠ 紙の上の区切り記号・外側の括弧・全角と半角の違いは、選択肢の表記に合わせて捨てます。
  ⚠ **どの選択肢にも丸が無ければ null** です。当てずっぽうで選んではいけません。
  ⚠ 様式の注意書きに選択肢が挙がっていないときだけ、囲まれている語を印字のまま 1 つ返します。
- ⚠⚠ **場所は「表題のすぐ下で、どの枠にも囲まれていない 1 行」です。**
  罫線で囲まれた欄の中に並ぶ選択肢は**別の項目**です (実測で左上の枠の中の選択肢を返した実行がありました)。
- ⚠ **返すのは、印が掛かっている選択肢 1 つだけ**です。
  ⚠⚠ **選択肢をつなげて 1 つにしないでください。** 並んでいる選択肢は別々のものです。
  ⚠ 線は細く薄くかすれています。**選択肢の一部に掛かっているだけでも印**とみなしてください
    (はっきり閉じた楕円だけを探すと見落とします)。
- ⚠⚠ 丸の線の端は隣の選択肢にはみ出します。**かすめているだけの選択肢と囲まれている選択肢を区別し、
  囲まれているほうを 1 つ返してください。** 印が 2 つに掛かって見えても**両方を返さない**でください。
- ⚠⚠ **手書きの丸と、印字された丸括弧を取り違えないでください。** 行の全体が括弧でくくられている
  ことがありますが、**外側の括弧は印字**であって選択の印ではありません。
- ⚠ 拡大した画像が添えられているときは、**その行が写っている拡大画像を必ず見てください。**
`,
      rules: `
7. **この紙の図は見なくてかまいません。** 完成イメージ・刻印の位置・寸法の参考図が並んでいますが、
   **図の場所を答えるのは別の仕事**です。ここでは**文字だけ**を読んでください。
8. **次のものは読みません。** 完成重量の内訳・希望原価・メッキ指定・ロゴ刻印・原型番号・石の指定も
   印字されていますが、**ORDER SHEET に出さないので読みません。**
`,
    },
    formNotes,
  );
}
