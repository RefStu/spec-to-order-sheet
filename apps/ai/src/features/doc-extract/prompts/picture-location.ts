import { buildPrompt } from "./layout";

/**
 * ノード④: 依頼書 **1 枚**の中で、**代表の図がどこにあるか**だけを答える。
 *
 * ⚠⚠ **このノードは座標しか聞かない。** specNo・品位・品名・区分と同じ呼び出しで
 *   聞いていたころ、実行ごとにどれかが落ちていた (実測)。
 *
 * ⚠⚠ **選ぶ基準は「並んでいる図のいちばん左上」**。
 *   ORDER SHEET の Picture に入れるのは「完成イメージ」ではない。
 *   - ⚠ 実物の p2 では `※隙間部分の形状参考` が選ばれる (完成イメージは左から 3 番目)。
 *     **これは仕様どおりで、外れではない。** p3 は `(完成イメージ)` が左端なので一致する。
 *   - ⚠ **ラベルを軸にした文は戻さないこと。** 新しい方針と正面から矛盾する。
 *
 * ⚠⚠ **文面から「大きさの指示」を全部落とした。**
 *   切り出した絵に**隣の図が写る / 絵が見切れる**のは、注意書きが多すぎて狙いが薄まって
 *   いるため、という判断。**サイズを数字で指示しない。** 落としたのは
 *   「升目 1 つ」「おおむね 1 %、多くても 2 %」「0.02 を超えたら囲みすぎ」「ページの半分」
 *   「枠線も手がかりにしない」「最後に見直して狭める」「枠の上端は絵そのものの上端」。
 *   - ⚠⚠ **これは承知のうえで取ったリスク。** 過去の実測 (面積):
 *     ラベル軸 **0.0048 / 0.0080** → 位置軸 **0.0132〜0.0156** →
 *     **大きさの文を場所の文ごと捨てた版は 0.0990** で `MAX_AREA_RATIO = 0.08` に弾かれ、
 *     **1 枚も切り出せなかった**。今回は場所の文は残してある。
 *   - **戻したくなったら、落とした文面は git から丸ごと拾える**:
 *     (このファイルの履歴を辿る)。⚠ 戻すなら**まず実測を取り直す**こと。閾値 (`lib/picture-box.ts`) は触らない。
 *
 * ⚠⚠ **実測 — 短くしても悪くならないが、良くもならない。**
 *   実物のサンプル (非公開) を **gpt-5-mini で 6 回**流した。
 *   - **場所は当たる。** x ≒ 0.06〜0.12 / y ≒ 0.56〜0.62 で、狙いの図の上に乗る。
 *     **6 回とも 2 枚とも切り出せた** (面積 0.0120〜0.0273。`MAX_AREA_RATIO` に遠い)。
 *     ＝ 短くしたことによる**退行は無い** (長かったころの実測は 0.0132〜0.0156)。
 *   - ⚠⚠ **直っていないのは「枠が縦に伸びる」ほう。** 目で測った実物 (p2 の
 *     `※隙間部分の形状参考`) は **x 0.088 / y 0.585 / w 0.112 / h 0.072** (面積 0.0080、
 *     横長で aspect 1.55)。モデルの答えは **w はほぼ合うのに h が 1.7〜2.9 倍**で、
 *     **6 回中 4 回が w = h の正方形** (0.120 × 0.120 など)。
 *     結果、切り出した絵に**下の段の図が写る / 上が見切れる**。
 *   - ⚠ **文面では動かなかった。** 「枠の上端と下端は絵そのものの上端と下端」
 *     「下に並んでいる次の図まで伸ばさない」を足して 3 回流したが、
 *     **3 回とも aspect 1.00 のまま**だった (だから足さずに戻した)。
 *   - ⚠ **モデルを上げても解決しない。** `openai/gpt-5` は p3 で良くなった
 *     (aspect 2.15 / 面積 0.0091) が、p2 では**図 4 つ**をまとめて囲んだ (面積 0.0255)。
 *   ⚠⚠ **つまり、残りは指示文の問題ではなく「座標を当てる」能力の問題。**
 *     次に試すなら文面ではなく**渡し方**のほう: いま渡しているのは
 *     「ページ全体 + 帯 6 本」で、モデルは**帯で見た位置をページの割合へ頭の中で
 *     戻して**いる (答えが 0.01 刻みの丸い値になるのはこのため)。
 *     **帯の中での割合を答えさせ、ページの割合へはコードで直す**のが筋
 *     (`lib/page-images.ts` の `zoomBands()` が帯の y 範囲を持っている)。
 *
 * ⚠⚠ **大きさはコードで直すことにした。** モデルの枠を種にして、
 *   **白地の上の白以外の塊**に寄せてから切る (`lib/snap-box.ts`)。実測 3 回で、p2・p3 とも
 *   枠の形がどれだけずれていても**図 1 つちょうど**に寄った。
 *   - ⚠ そのため**文面は変えていない。** 「図は白地の上の白以外の塊」と足す案は、
 *     寄せる処理だけで足りたので入れていない (効いた実測が無いものは足さない)。
 *   - ⚠ ここで大事なのは**場所**のほう。寄せる処理は種と重なる塊しか見ないので、
 *     種が別の図の上に乗っていれば、その図に寄る (選ぶのはモデル、大きさはコード)。
 *   - ⚠ 「6 回中 4 回が正方形」の正方形は**割合での**正方形で、A4 の画素では
 *     1 : 1.41 の縦長になる。紙の図と比率が合わなかったのはこのため (`lib/snap-box.ts` の冒頭)。
 *
 * ⚠ **「割合はページ全体の画像に対するもの」の 1 行は消さないこと。**
 *   帯 (`steps/locate-pictures.ts` の `PICTURE_ZOOM_BANDS = 6`) を一緒に渡しているので、
 *   基準を言わないと**帯を 1 とした座標**が返りうる。
 *
 * @param formNotes その様式にだけ効く注意書き (= 担当位置)。**様式が分からなければ空文字**。
 */
export function pictureLocationPrompt(formNotes = ""): string {
  return buildPrompt(
    {
      overview: `
依頼書 1 枚が渡されます。この紙に並んでいる**写真・イラスト**のうち、
**いちばん左上の 1 つ**を囲む四角の座標を答えてください。

⚠ **欄の値は読みません。** 仕様書No も品位も品名も**別の仕事**です。答えるのは座標だけです。
`,
      fields: `
| 欄 | 何の値か |
| --- | --- |
| pictures[].page | PDF 全体の通し番号。添えられた「n ページ目」のとおり |
| pictures[].x / y / width / height | 選んだ図を囲む四角。**添付されたページ全体の画像**の幅と高さを 1 とした割合で、x / y は**左上** |
| pictures[].labelQuote | 選んだ図に添えられているラベルの**印字そのまま**。無ければ null |
| pictures[].confidence | その 1 つの自信 (0〜100) |

## 手順

1. 紙に並んでいる**写真とイラストを全部**見つけます。
   ⚠ 会社のロゴ・印・表の罫線・文字だけの枠は図ではありません。
2. そのうち**いちばん左上の 1 つ**を選びます。**選ぶのは 1 つだけです。**
3. その 1 つの**絵の部分だけ**を四角で囲みます。
   **ラベルや説明の文字、隣の図は入れません。**
4. 図が 1 つも見つからなければ**空の配列**にします。当てずっぽうの座標を返してはいけません。
`,
    },
    formNotes,
  );
}
