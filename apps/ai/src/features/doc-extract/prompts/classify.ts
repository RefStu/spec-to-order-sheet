import { buildPrompt } from "./layout";

/** 分類のプロンプトに出す様式 1 つぶん。**一覧の正は `prompts/index.ts` の表。** */
export interface FormSection {
  /** `FORM1` のような符号。**モデルにはこれを返させる。** */
  code: string;
  /** 「様式パターン①」のような呼び名。 */
  name: string;
  /** その様式の**見分け方**。`###` の節の中身になる。 */
  notes: string;
}

/** `### 様式パターン①（code: FORM1）` の節を作る。 */
function formSection(form: FormSection): string {
  return [`### ${form.name}（code: ${form.code}）`, form.notes.trim()].join("\n\n");
}

/**
 * ノード①: 分類。**値は読まない。**
 *
 * ⚠⚠ ここが決めるのは「**どの様式か**」と「**どのページがどの部品か**」。
 * ⚠ **全ページを低い解像度で渡している。** 表題と見出しと紙の形しか見ないので足りる。
 * ⚠ 様式の差分は**本文の中**に一覧として出る (末尾に足す他の役割とは形が違う)。
 */
export function classifyPromptFor(forms: readonly FormSection[]): string {
  return buildPrompt({
    overview: `
渡された画像は、お客様から **1 回の発注として届いた帳票の束**です。次の 2 つを答えます。

1. この束が**どの様式か**を、下の一覧から **1 つだけ**選ぶ
2. **ページ 1 枚ずつ**が何の紙かを答える

**欄の値は読みません。** 各ページの**いちばん上に印字された表題・見出し**と、紙の形だけを見てください。
`,
    fields: `
## ページの見分け方 (pages)

**渡された画像 1 枚につき 1 要素**を、必ず全ページぶん返します。

| 欄 | 何の値か | どこから取るか |
| --- | --- | --- |
| page | PDF 全体の通し番号 | 添えられた「n ページ目」のとおり |
| headerQuote | そのページの表題・見出し | **いちばん上に印字されているものをそのまま**。⚠ 読めなければ null。**でっち上げないでください** |
| docType | その紙の種類 | 下の 3 つから 1 つ |
| startsNewSheet | 新しい 1 枚の 1 ページ目か | 下を参照 (docType が spec_sheet のときだけ意味を持ちます) |
| confidence | その 1 枚の判断の自信 (0〜100) | — |

- docType の 3 つ
  - **purchase_order** … **発注書**。品名・数量・サイズ・納期の列を持つ**明細の表**が載っている紙
  - **spec_sheet** … **新製品依頼書**。1 つの品物について品位・石の指定・完成イメージを書いた紙
  - **other** … どちらとも言えない紙 (送り状・工程表・白紙など)
- startsNewSheet … そのページに**表題と仕様書No が印字されていれば true** (= 新しい 1 枚の 1 ページ目)。
  前のページの続き (裏面や、表の続きだけの紙) なら false。
  ⚠⚠ **同じ形の紙が何枚も続きます。1 枚ずつ別の品物です。**
  迷ったら **true** にしてください (別々に読むほうが、2 枚を 1 枚にまとめるより安全です)。

⚠⚠ **依頼書は「別の帳票」ではありません。** 多くの様式では、**発注書 1 通に依頼書が添えられて
1 通の PDF で届きます**。

## 様式の選び方 (formCode)

下の \`###\` の見出しから、この束に当てはまるものを **1 つだけ**選び、その **code** を返します。

- ⚠ **一覧に無い code を作ってはいけません。** 当てはまるものが無ければ **null** です。
- ⚠ **ページごとに違う様式を選んではいけません。** 様式は束全体に 1 つです。
- formConfidence は、その様式を選んだことにどれくらい自信があるかです。
  候補が 1 つしか無いからという理由で高くしないでください。

${forms.length === 0 ? "（様式の一覧はありません。formCode は必ず null にしてください。）" : forms.map(formSection).join("\n\n")}
`,
  });
}
