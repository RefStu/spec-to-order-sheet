import { buildPrompt } from "./layout";

/**
 * ノード⑤: **発注書の明細と依頼書の対応づけ**だけを確かめる。
 *
 * ⚠⚠ **突き合わせの規則はここに書かない。** 正規化の規則 (全角・ハイフン・年の桁) の正は
 *   web 側の `order-sheets/lib/spec-no.ts` の `matchBySpecNo()` にあり、**決定的**に動く。
 *   ここに同じ規則を書くと、その日から 2 つが少しずつずれていく。
 *   このノードが受け持つのは「**規則では結べなかったものを、人が目で見るように結ぶ**」ところだけ。
 * ⚠ 画像は渡さない (読み取った印字だけを見て答える)。
 */
export function linkPrompt(): string {
  return buildPrompt({
    overview: `
1 通の PDF から読み取った、**発注書の明細**と**新製品依頼書**の一覧が渡されます。
**どの明細がどの依頼書のものか**を答えてください。
`,
    fields: `
| 欄 | 何の値か | どう決めるか |
| --- | --- | --- |
| lineNo | 発注書の明細の番号 | 渡された一覧のとおり。⚠ **すべての明細を 1 件ずつ**答えます (結べなかったものも省かない) |
| specSheetIndex | 結びついた依頼書 | 下の「結び方」。結べなければ null |
| matchedBy | 何で結んだか | spec_no (番号) / product_name (品名) / other。結べなければ null |
| confidence | その 1 件の結びつきの自信 (0〜100) | — |

## 結び方

- **仕様書No と製造番号が同じもの**を結びます。これがいちばん強い手がかりです。
  ⚠ 番号の書き方の揺れ (区切り記号・全角と半角・年の桁数) は**同じ番号とみなしてかまいません**。
- 番号で結べない明細は、**品名**が指している品物が同じかどうかで判断してください。
- ⚠⚠ **迷ったら結ばないでください。** specSheetIndex を null にするほうが、
  間違った依頼書を結ぶより**ずっと良い**結果です。
- ⚠ **同じ品物を複数の明細で頼むことがあります。** そのときは**どの明細も同じ依頼書**を指すのが正しいです。
`,
  });
}
