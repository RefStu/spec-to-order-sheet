import { buildPrompt } from "./layout";

/**
 * ノード⑤: 依頼書 **1 枚**の**いちばん下に印字されたメモ**だけを読む。
 *
 * ⚠⚠ **将来は消す機能。** 目的は「AI が紙から本当に値を読めている」ことの証明
 *   (消し方は `contract.ts` の `specNoteFields` の注記)。
 * ⚠⚠ **指示文に実際の値を書かないこと。** 値を書くと、読めたのか写したのかが
 *   区別できなくなり、証明にならない。書いてよいのは**ラベル名**と**場所の言葉**だけ
 *   (`prompts.test.ts` の「実際の値が指示文に無い」が固定している)。
 * ⚠⚠ **依頼書の欄のノード (`spec-sheet.ts`) には足さない。** 同じ呼び出しに詰めると
 *   区分が再び落ちうる (実測)。
 * ⚠ 「手書きは読まない」の共通の規則は**変えない**。メモは活字なので今の規則のままで読める。
 */
export function specNotePrompt(): string {
  return buildPrompt({
    overview: `
依頼書 **1 枚**が渡されます。この紙の**いちばん下の、表の外の余白**に、
\`ラベル : 値\` の形の**メモ**が 1 行ずつ印字されていることがあります。
**そのメモだけ**を読み、下の 5 欄を取り出します。

⚠ **メモが無い紙もあります。** そのときは 5 欄とも null です。
`,
    rules: `
7. **読むのはメモの行だけです。** 表の中の欄 (品位・石の指定・メッキ指定・ロゴ刻印 など) に
   似た内容が印字されていても、**そこから値を取ってはいけません。**
   ラベルの行がメモに無ければ、その欄は null です。
8. **ラベルは完全に一致するものだけ**を使います。番号の違う \`Description\` は別の欄です。
9. **value も quote も、\`:\` の右側を行の終わりまで印字そのまま**写します。
   記号・括弧・空白・日本語以外の文字も**見えるとおり**に残し、翻訳も言い換えもしません。
`,
    fields: `
| 欄 | どのラベルの行か |
| --- | --- |
| sizeText | \`Size\` |
| stoneText | \`STONE\` |
| description2 | \`Description#2\` |
| description3 | \`Description#3\` |
| description4 | \`Description#4\` |

- page は、その行が印字されているページ (添えられた「n ページ目」のとおり)。
- ⚠ 拡大した画像が添えられているときは、**紙のいちばん下が写っている拡大画像を必ず見てください。**
`,
  });
}
